def _cubic(o0: np.ndarray, v0: np.ndarray, o1: np.ndarray, v1: np.ndarray, T: float) -> np.ndarray:
    """Coefficients (4, 3) of the cubic from (o0, v0) to (o1, v1) over duration T."""
    T = max(T, 1e-3)
    c2 = (3 * (o1 - o0) - (2 * v0 + v1) * T) / T**2
    c3 = (2 * (o0 - o1) + (v0 + v1) * T) / T**3
    return np.stack([o0, v0, c2, c3])


class MinTimeController(Controller):
    """Track the embedded minimum-time plan with online gate corrections."""

    kp = np.array([12.0, 12.0, 16.0])  # m/s^2 per m
    kd = np.array([6.0, 6.0, 7.0])  # m/s^2 per m/s
    ki = 2.0
    ff_lead = 0.06  # s, plan acceleration is taken this far ahead (attitude lag)
    max_tilt_deg = 65.0
    thrust_frac = 0.97  # of the maximum collective thrust
    correct_frac = 1.0  # fraction of a revealed gate shift that is corrected
    # progress governor: the reference clock runs at `rate` x real time, slowing when the drone
    # is behind the reference along the path and speeding up (a little) when it is ahead
    gov_gain = 3.0  # rate change per metre of along-track error
    rate_min, rate_max = 0.4, 1.1
    rate_slew = 4.0  # max rate change per second
    gov_bias = 0.05  # m; the steady along-track lag that is accepted without slowing down
    # gate approach: within `approach_window` s (plan time) of a crossing, cap the clock rate, so a
    # gate revealed late leaves more time for the correction
    # per passage (gates 1, 2, 3, 4, 2), learned with CMA-ES in rl_spline/tune_es.py (run brake1)
    approach_window = (0.592, 0.632, 0.459, 0.536, 0.512)
    approach_rate = (0.713, 0.768, 0.598, 0.571, 0.72)
    # lag predictor: feedback acts on the state predicted `predict` s ahead (current velocity and
    # current thrust direction), compared with the reference at that time
    predict = 0.0

    def __init__(self, obs: dict[str, NDArray[np.floating]], info: dict, config: dict):
        """Rebuild the reference from the embedded plan and set up gate corrections."""
        super().__init__(obs, info, config)
        if config.env.control_mode != "attitude":
            raise ValueError("MinTimeController requires control_mode = 'attitude'")
        p = load_params(config.sim.dynamics, config.sim.drone)
        self.mass = p["mass"]
        self.a_max = 4 * p["thrust_max"] / self.mass
        self.dt = 1 / config.env.freq
        self.t = 0.0  # reference (plan) clock
        self.rate = 1.0
        self._last_thrust = 0.0
        # reference: exact integration of the piecewise-constant plan accelerations
        n = len(PLAN_A) // len(PLAN_T)
        self.step_dt = np.repeat(PLAN_T / n, n)
        self.knots = np.r_[0.0, np.cumsum(self.step_dt)]
        self.ref_p = np.zeros((len(PLAN_A) + 1, 3))
        self.ref_v = np.zeros((len(PLAN_A) + 1, 3))
        self.ref_p[0] = PLAN_P0
        for k, dt in enumerate(self.step_dt):
            a = PLAN_A[k] + GRAVITY
            self.ref_p[k + 1] = self.ref_p[k] + self.ref_v[k] * dt + 0.5 * a * dt**2
            self.ref_v[k + 1] = self.ref_v[k] + a * dt
        self.gate_t = np.cumsum(PLAN_T)  # planned crossing time of each passage
        self.sequence = np.asarray(obs["gate_sequence"], dtype=int)
        self.nominal = np.array([g["pos"] for g in config.env.track.gates], dtype=float)
        self.known = np.zeros(len(self.nominal), dtype=bool)
        self.shift = np.zeros_like(self.nominal)
        self.reveal_t = np.full(len(self.nominal), -1.0)
        self.integral = np.zeros(3)
        # offset path: starts at the measured start offset, fades to the first gate's shift
        self.segment = 0
        self._plan_offset(np.asarray(obs["pos"]) - PLAN_P0, np.zeros(3), 0.0)
        self.finished = False

    # --- reference ----------------------------------------------------------------------------
    def _ref(self, t: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Plan position, velocity and thrust acceleration at time t."""
        if t >= self.knots[-1]:
            return self.ref_p[-1] + self.ref_v[-1] * (t - self.knots[-1]), self.ref_v[-1], -GRAVITY
        k = int(np.searchsorted(self.knots, t, side="right") - 1)
        tau = t - self.knots[k]
        a = PLAN_A[k] + GRAVITY
        return self.ref_p[k] + self.ref_v[k] * tau + 0.5 * a * tau**2, self.ref_v[k] + a * tau, PLAN_A[k]

    def _target(self, passage: int) -> np.ndarray:
        """Offset to aim for at a passage: the gate's revealed shift (zero while unseen)."""
        if passage >= len(self.sequence):
            return np.zeros(3)
        return self.correct_frac * self.shift[self.sequence[passage]]

    def _plan_offset(self, o0: np.ndarray, v0: np.ndarray, t: float):
        end = self.gate_t[min(self.segment, len(self.gate_t) - 1)]
        self.off_t0 = t
        self.off_T = end - t
        self.off_c = _cubic(o0, v0, self._target(self.segment), np.zeros(3), self.off_T)

    def _offset(self, t: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        tau = min(max(t - self.off_t0, 0.0), max(self.off_T, 0.0))
        c = self.off_c
        o = c[0] + c[1] * tau + c[2] * tau**2 + c[3] * tau**3
        v = c[1] + 2 * c[2] * tau + 3 * c[3] * tau**2
        a = 2 * c[2] + 6 * c[3] * tau
        if t - self.off_t0 > self.off_T:  # past the end: hold the final offset
            v, a = np.zeros(3), np.zeros(3)
        return o, v, a

    # --- control ------------------------------------------------------------------------------
    def compute_control(
        self, obs: dict[str, NDArray[np.floating]], info: dict | None = None
    ) -> NDArray[np.floating]:
        """Return [roll, pitch, yaw, collective thrust]."""
        t = self.t
        replan = False
        visited = np.asarray(obs["gates_visited"], dtype=bool)
        for g in np.flatnonzero(visited & ~self.known):
            self.known[g] = True
            self.shift[g] = np.asarray(obs["gates_pos"][g]) - self.nominal[g]
            self.reveal_t[g] = t
            replan = True
        segment = int(min(np.searchsorted(self.gate_t, t, side="right"), len(self.gate_t)))
        if segment != self.segment:
            self.segment, replan = segment, True
        if replan and self.segment < len(self.gate_t):
            o, v, _ = self._offset(t)
            self._plan_offset(o, v, t)

        pos, vel = np.asarray(obs["pos"], dtype=float), np.asarray(obs["vel"], dtype=float)
        L = self.predict
        if L > 0:  # where the drone will be once the current attitude has acted for L seconds
            z_now = Rotation.from_quat(obs["quat"]).as_matrix()[:, 2]
            a_now = z_now * self._last_thrust / self.mass + GRAVITY
            pos, vel = pos + vel * L + 0.5 * a_now * L**2, vel + a_now * L
        tL = t + L * self.rate
        p_ref, v_ref, _ = self._ref(tL)
        _, _, a_ff = self._ref(tL + self.ff_lead * self.rate)
        o, ov, _ = self._offset(tL)
        _, _, oa_lead = self._offset(tL + self.ff_lead * self.rate)
        e = p_ref + o - pos
        # governor: compare along-track position, adapt the clock rate
        tangent = v_ref + ov
        speed = np.linalg.norm(tangent)
        along = float(-e @ tangent / speed) if speed > 0.3 else 0.0  # > 0: drone is ahead
        target = np.clip(1.0 + self.gov_gain * (along + self.gov_bias), self.rate_min, self.rate_max)
        if self.segment < len(self.gate_t):
            # per-passage values allowed (learned schedule); a scalar applies to every passage
            window = float(np.broadcast_to(self.approach_window, len(self.gate_t))[self.segment])
            cap = float(np.broadcast_to(self.approach_rate, len(self.gate_t))[self.segment])
            g = self.sequence[self.segment]  # skip gates whose position was known well before
            fresh = not self.known[g] or self.reveal_t[g] > self.gate_t[self.segment] - window - 0.3
            if self.gate_t[self.segment] - t < window and fresh:
                target = min(target, cap)
        step = self.rate_slew * self.dt
        self.rate = float(np.clip(target, self.rate - step, self.rate + step))
        r = self.rate
        ev = (v_ref + ov) * r - vel
        self.integral = np.clip(self.integral + e * self.dt, -0.3, 0.3)
        kinematic = (a_ff + GRAVITY + oa_lead) * r**2  # plan acceleration at the current rate
        acc = kinematic - GRAVITY + self.kp * e + self.kd * ev + self.ki * self.integral

        # limits: thrust magnitude and tilt
        acc[2] = max(acc[2], 0.5)
        tan_max = np.tan(np.deg2rad(self.max_tilt_deg))
        lateral = np.linalg.norm(acc[:2])
        if lateral > acc[2] * tan_max:
            acc[:2] *= acc[2] * tan_max / lateral
        norm = np.linalg.norm(acc)
        if norm > self.thrust_frac * self.a_max:
            acc *= self.thrust_frac * self.a_max / norm

        z_body = Rotation.from_quat(obs["quat"]).as_matrix()[:, 2]
        thrust = self.mass * max(float(acc @ z_body), 0.0)
        self._last_thrust = thrust
        z_des = acc / np.linalg.norm(acc)
        y_des = np.cross(z_des, [1.0, 0.0, 0.0])
        y_des /= np.linalg.norm(y_des)
        x_des = np.cross(y_des, z_des)
        rpy = Rotation.from_matrix(np.c_[x_des, y_des, z_des]).as_euler("xyz")
        return np.r_[rpy, thrust].astype(np.float32)

    def step_callback(self, action, obs, reward, terminated, truncated, info) -> bool:  # noqa: D102
        self.t += self.dt * self.rate
        return int(obs["n_gates_passed"]) >= len(self.sequence)

    def episode_callback(self):
        """Reset between episodes."""
        self.t, self.rate = 0.0, 1.0
        self.integral[:] = 0
