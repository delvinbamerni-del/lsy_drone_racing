# --- MPC tracker (acados, so_rpy model incl. attitude dynamics) ------------------------------
_MPC_CACHE: dict = {}


def _accel_to_rpy(acc: np.ndarray) -> np.ndarray:
    """Roll/pitch with yaw exactly 0 (extrinsic xyz) that point the body z-axis along `acc`.

    With R = Ry(pitch) Rx(roll): z = [cos(r) sin(p), -sin(r), cos(r) cos(p)].
    """
    z = acc / np.linalg.norm(acc)
    return np.array([-np.arcsin(np.clip(z[1], -1, 1)), np.arctan2(z[0], z[2]), 0.0])


# frame keep-out points on the gate square (half-size 0.28 m = centre line of the collision boxes)
_EDGE = np.array([-0.28, -0.14, 0.0, 0.14])
FRAME_LOCAL = np.r_[np.c_[_EDGE, np.full(4, 0.28)], np.c_[np.full(4, 0.28), -_EDGE],
                    np.c_[-_EDGE, np.full(4, -0.28)], np.c_[np.full(4, -0.28), _EDGE]]  # (lat, up)
N_FRAME = 2 * len(FRAME_LOCAL)  # the gate just passed and the next gate


def _build_mpc(drone: str, N: int, dt: float, weights: tuple, tilt: float, n_poles: int = 4,
               pole_r: float = 0.0, pole_penalty: float = 1e3, frame_r: float = 0.0):
    """Compile (once per process and setting) an acados tracking MPC.

    pole_r > 0 adds soft keep-out constraints around every pole (vertical line at a parameter
    position): (x - px)^2 + (y - py)^2 >= pole_r^2.
    """
    key = (drone, N, dt, weights, tilt, n_poles, pole_r, pole_penalty, frame_r)
    if key in _MPC_CACHE:
        return _MPC_CACHE[key]
    import os

    import scipy.linalg
    from acados_template import AcadosModel, AcadosOcp, AcadosOcpSolver
    from crazyflow.dynamics import Dynamics
    from crazyflow.dynamics.so_rpy import symbolic_dynamics_euler

    p = load_params(Dynamics.so_rpy, drone)
    X_dot, X, U, _ = symbolic_dynamics_euler(
        mass=p["mass"], gravity_vec=p["gravity_vec"], acc_coef=p["acc_coef"],
        cmd_f_coef=p["cmd_f_coef"], rpy_coef=p["rpy_coef"], rpy_rates_coef=p["rpy_rates_coef"],
        cmd_rpy_coef=p["cmd_rpy_coef"],
    )
    import casadi as ca

    # the command u is part of the state; the optimiser chooses its rate du (smooth commands)
    dU = type(U).sym("du", U.rows())  # same symbolic type (SX or MX) as the model
    tag = f"rl_mpc_{os.getpid()}_{len(_MPC_CACHE)}"
    model = AcadosModel()
    model.name = tag
    model.x = ca.vertcat(X, U)
    model.u = dU
    model.f_expl_expr = ca.vertcat(X_dot, dU)
    ocp = AcadosOcp()
    ocp.model = model
    nx, nu = X.rows() + U.rows(), U.rows()
    ocp.solver_options.N_horizon = N
    ocp.solver_options.tf = N * dt
    ocp.cost.cost_type = ocp.cost.cost_type_e = "LINEAR_LS"
    wp, wa, wv, wr, wu_a, wu_t, wd_a, wd_t = weights
    Q = np.diag([wp, wp, wp, wa, wa, wa, wv, wv, wv, wr, wr, wr, wu_a, wu_a, wu_a, wu_t])
    R = np.diag([wd_a, wd_a, wd_a, wd_t])
    ocp.cost.W, ocp.cost.W_e = scipy.linalg.block_diag(Q, R), Q
    ocp.cost.Vx = np.vstack([np.eye(nx), np.zeros((nu, nx))])
    ocp.cost.Vu = np.vstack([np.zeros((nx, nu)), np.eye(nu)])
    ocp.cost.Vx_e = np.eye(nx)
    ocp.cost.yref, ocp.cost.yref_e = np.zeros(nx + nu), np.zeros(nx)
    ocp.constraints.idxbx = np.array([3, 4, 12, 13, 14, 15])
    ocp.constraints.lbx = np.array([-tilt, -tilt, -tilt, -tilt, -0.3, 4 * p["thrust_min"]])
    ocp.constraints.ubx = np.array([tilt, tilt, tilt, tilt, 0.3, 4 * p["thrust_max"]])
    ocp.constraints.idxbu = np.arange(4)
    ocp.constraints.lbu = np.array([-20.0, -20.0, -5.0, -20.0])  # rad/s and N/s
    ocp.constraints.ubu = -ocp.constraints.lbu
    ocp.constraints.x0 = np.zeros(nx)
    if pole_r > 0 or frame_r > 0:  # soft keep-outs; obstacle positions are runtime parameters
        P = type(U).sym("obstacles", 2 * n_poles + 3 * N_FRAME)
        model.p = P
        ocp.parameter_values = np.zeros(2 * n_poles + 3 * N_FRAME)
        h, lo = [], []
        if pole_r > 0:
            h += [(X[0] - P[2 * i]) ** 2 + (X[1] - P[2 * i + 1]) ** 2 for i in range(n_poles)]
            lo += [pole_r**2] * n_poles
        if frame_r > 0:
            o = 2 * n_poles
            h += [ca.sumsqr(X[0:3] - P[o + 3 * i:o + 3 * i + 3]) for i in range(N_FRAME)]
            lo += [frame_r**2] * N_FRAME
        nh = len(h)
        model.con_h_expr = ca.vertcat(*h)
        ocp.constraints.lh, ocp.constraints.uh = np.array(lo), np.full(nh, 1e3)
        ocp.constraints.idxsh = np.arange(nh)
        ocp.cost.zl = ocp.cost.Zl = np.full(nh, pole_penalty)
        ocp.cost.zu = ocp.cost.Zu = np.zeros(nh)
    ocp.solver_options.qp_solver = "PARTIAL_CONDENSING_HPIPM"
    ocp.solver_options.hessian_approx = "GAUSS_NEWTON"
    ocp.solver_options.integrator_type = "ERK"
    ocp.solver_options.nlp_solver_type = "SQP"
    ocp.solver_options.nlp_solver_max_iter = 10
    ocp.solver_options.qp_solver_iter_max = 30
    ocp.code_export_directory = f"c_generated_code/{tag}"
    solver = AcadosOcpSolver(ocp, json_file=f"c_generated_code/{tag}.json", verbose=False)
    _MPC_CACHE[key] = (solver, nx, nu)
    return _MPC_CACHE[key]


def _cubic(o0: np.ndarray, v0: np.ndarray, o1: np.ndarray, v1: np.ndarray, T: float) -> np.ndarray:
    """Coefficients (4, 3) of the cubic from (o0, v0) to (o1, v1) over duration T."""
    T = max(T, 1e-3)
    c2 = (3 * (o1 - o0) - (2 * v0 + v1) * T) / T**2
    c3 = (2 * (o0 - o1) + (v0 + v1) * T) / T**3
    return np.stack([o0, v0, c2, c3])


class MinTimeController(Controller):
    """Track the embedded minimum-time plan with online gate corrections."""

    kp = np.array([12.0, 12.0, 16.0])  # m/s^2 per m
    kd = np.array([6.0, 6.0, 7.0])  # m/s^2 per m/s
    ki = 2.0
    ff_lead = 0.06  # s, plan acceleration is taken this far ahead (attitude lag)
    max_tilt_deg = 65.0
    thrust_frac = 0.97  # of the maximum collective thrust
    correct_frac = 1.0  # fraction of a revealed gate shift that is corrected
    # progress governor: the reference clock runs at `rate` x real time, slowing when the drone
    # is behind the reference along the path and speeding up (a little) when it is ahead
    gov_gain = 3.0  # rate change per metre of along-track error
    rate_min, rate_max = 0.4, 1.1
    rate_slew = 4.0  # max rate change per second
    gov_bias = 0.05  # m; the steady along-track lag that is accepted without slowing down
    # gate approach: within `approach_window` s (plan time) of a crossing, cap the clock rate, so a
    # gate revealed late leaves more time for the correction
    # per passage (gates 1, 2, 3, 4, 2), learned with CMA-ES in rl_spline/tune_es.py (run brake1)
    approach_window = (0.592, 0.632, 0.459, 0.536, 0.512)
    approach_rate = (0.713, 0.768, 0.598, 0.571, 0.72)
    # after a gate is revealed, release the brake if its shift across the opening is small:
    # cap = approach_rate + (1 - approach_rate) * clip((release_s1 - s) / (release_s1 - release_s0))
    release_s0, release_s1 = 0.0, 0.0  # m; s <= s0: full release, s >= s1: full brake (off: 0, 0)
    # lag predictor: feedback acts on the state predicted `predict` s ahead (current velocity and
    # current thrust direction), compared with the reference at that time
    predict = 0.0
    # MPC tracker (acados, so_rpy model); off = the PID tracker above
    use_mpc = True
    mpc_N = 25  # horizon steps (x 1/50 s)
    # pos, rpy, vel, rpy-rates, cmd rpy, cmd thrust, cmd rpy rate, cmd thrust rate
    mpc_weights = (300.0, 2.0, 30.0, 1.0, 1.0, 100.0, 0.02, 0.2)
    mpc_pole_r = 0.20  # m, soft keep-out radius around poles (0 = off)
    mpc_pole_penalty = 1e3
    mpc_frame_r = 0.22  # m, soft keep-out radius around gate frame points (0 = off)

    def __init__(self, obs: dict[str, NDArray[np.floating]], info: dict, config: dict):
        """Rebuild the reference from the embedded plan and set up gate corrections."""
        super().__init__(obs, info, config)
        if config.env.control_mode != "attitude":
            raise ValueError("MinTimeController requires control_mode = 'attitude'")
        p = load_params(config.sim.dynamics, config.sim.drone)
        self.mass = p["mass"]
        self._drone = config.sim.drone
        self._mpc_warm = False
        self._last_u = np.array([0.0, 0.0, 0.0, self.mass * 9.81])
        self.a_max = 4 * p["thrust_max"] / self.mass
        self.dt = 1 / config.env.freq
        self.t = 0.0  # reference (plan) clock
        self.rate = 1.0
        self._last_thrust = 0.0
        # reference: exact integration of the piecewise-constant plan accelerations
        n = len(PLAN_A) // len(PLAN_T)
        self.step_dt = np.repeat(PLAN_T / n, n)
        self.knots = np.r_[0.0, np.cumsum(self.step_dt)]
        self.ref_p = np.zeros((len(PLAN_A) + 1, 3))
        self.ref_v = np.zeros((len(PLAN_A) + 1, 3))
        self.ref_p[0] = PLAN_P0
        for k, dt in enumerate(self.step_dt):
            a = PLAN_A[k] + GRAVITY
            self.ref_p[k + 1] = self.ref_p[k] + self.ref_v[k] * dt + 0.5 * a * dt**2
            self.ref_v[k + 1] = self.ref_v[k] + a * dt
        self.gate_t = np.cumsum(PLAN_T)  # planned crossing time of each passage
        self.sequence = np.asarray(obs["gate_sequence"], dtype=int)
        self.nominal = np.array([g["pos"] for g in config.env.track.gates], dtype=float)
        self.known = np.zeros(len(self.nominal), dtype=bool)
        self.shift = np.zeros_like(self.nominal)
        self.reveal_t = np.full(len(self.nominal), -1.0)
        self.integral = np.zeros(3)
        # offset path: starts at the measured start offset, fades to the first gate's shift
        self.segment = 0
        self._plan_offset(np.asarray(obs["pos"]) - PLAN_P0, np.zeros(3), 0.0)
        self.finished = False

    # --- reference ----------------------------------------------------------------------------
    def _ref(self, t: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Plan position, velocity and thrust acceleration at time t."""
        if t >= self.knots[-1]:
            return self.ref_p[-1] + self.ref_v[-1] * (t - self.knots[-1]), self.ref_v[-1], -GRAVITY
        k = int(np.searchsorted(self.knots, t, side="right") - 1)
        tau = t - self.knots[k]
        a = PLAN_A[k] + GRAVITY
        return self.ref_p[k] + self.ref_v[k] * tau + 0.5 * a * tau**2, self.ref_v[k] + a * tau, PLAN_A[k]

    def _target(self, passage: int) -> np.ndarray:
        """Offset to aim for at a passage: the gate's revealed shift (zero while unseen)."""
        if passage >= len(self.sequence):
            return np.zeros(3)
        return self.correct_frac * self.shift[self.sequence[passage]]

    def _plan_offset(self, o0: np.ndarray, v0: np.ndarray, t: float):
        end = self.gate_t[min(self.segment, len(self.gate_t) - 1)]
        self.off_t0 = t
        self.off_T = end - t
        self.off_c = _cubic(o0, v0, self._target(self.segment), np.zeros(3), self.off_T)

    def _offset(self, t: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        tau = min(max(t - self.off_t0, 0.0), max(self.off_T, 0.0))
        c = self.off_c
        o = c[0] + c[1] * tau + c[2] * tau**2 + c[3] * tau**3
        v = c[1] + 2 * c[2] * tau + 3 * c[3] * tau**2
        a = 2 * c[2] + 6 * c[3] * tau
        if t - self.off_t0 > self.off_T:  # past the end: hold the final offset
            v, a = np.zeros(3), np.zeros(3)
        return o, v, a

    # --- control ------------------------------------------------------------------------------
    def compute_control(
        self, obs: dict[str, NDArray[np.floating]], info: dict | None = None
    ) -> NDArray[np.floating]:
        """Return [roll, pitch, yaw, collective thrust]."""
        t = self.t
        replan = False
        visited = np.asarray(obs["gates_visited"], dtype=bool)
        for g in np.flatnonzero(visited & ~self.known):
            self.known[g] = True
            self.shift[g] = np.asarray(obs["gates_pos"][g]) - self.nominal[g]
            self.reveal_t[g] = t
            replan = True
        segment = int(min(np.searchsorted(self.gate_t, t, side="right"), len(self.gate_t)))
        if segment != self.segment:
            self.segment, replan = segment, True
        if replan and self.segment < len(self.gate_t):
            o, v, _ = self._offset(t)
            self._plan_offset(o, v, t)

        pos, vel = np.asarray(obs["pos"], dtype=float), np.asarray(obs["vel"], dtype=float)
        L = self.predict
        if L > 0:  # where the drone will be once the current attitude has acted for L seconds
            z_now = Rotation.from_quat(obs["quat"]).as_matrix()[:, 2]
            a_now = z_now * self._last_thrust / self.mass + GRAVITY
            pos, vel = pos + vel * L + 0.5 * a_now * L**2, vel + a_now * L
        tL = t + L * self.rate
        p_ref, v_ref, _ = self._ref(tL)
        _, _, a_ff = self._ref(tL + self.ff_lead * self.rate)
        o, ov, _ = self._offset(tL)
        _, _, oa_lead = self._offset(tL + self.ff_lead * self.rate)
        e = p_ref + o - pos
        # governor: compare along-track position, adapt the clock rate
        tangent = v_ref + ov
        speed = np.linalg.norm(tangent)
        along = float(-e @ tangent / speed) if speed > 0.3 else 0.0  # > 0: drone is ahead
        target = np.clip(1.0 + self.gov_gain * (along + self.gov_bias), self.rate_min, self.rate_max)
        if self.segment < len(self.gate_t):
            # per-passage values allowed (learned schedule); a scalar applies to every passage
            window = float(np.broadcast_to(self.approach_window, len(self.gate_t))[self.segment])
            cap = float(np.broadcast_to(self.approach_rate, len(self.gate_t))[self.segment])
            g = self.sequence[self.segment]  # skip gates whose position was known well before
            fresh = not self.known[g] or self.reveal_t[g] > self.gate_t[self.segment] - window - 0.3
            if self.gate_t[self.segment] - t < window and fresh:
                if self.known[g] and self.release_s1 > self.release_s0:
                    normal = Rotation.from_quat(obs["gates_quat"][g]).as_matrix()[:, 0]
                    across = self.shift[g] - (self.shift[g] @ normal) * normal
                    s = float(np.linalg.norm(across))
                    free = np.clip((self.release_s1 - s) / (self.release_s1 - self.release_s0), 0, 1)
                    cap = cap + (1.0 - cap) * free
                target = min(target, cap)
        step = self.rate_slew * self.dt
        self.rate = float(np.clip(target, self.rate - step, self.rate + step))
        r = self.rate
        ev = (v_ref + ov) * r - vel
        self.integral = np.clip(self.integral + e * self.dt, -0.3, 0.3)
        if self.use_mpc:
            return self._mpc_control(obs, t, r)
        kinematic = (a_ff + GRAVITY + oa_lead) * r**2  # plan acceleration at the current rate
        acc = kinematic - GRAVITY + self.kp * e + self.kd * ev + self.ki * self.integral

        # limits: thrust magnitude and tilt
        acc[2] = max(acc[2], 0.5)
        tan_max = np.tan(np.deg2rad(self.max_tilt_deg))
        lateral = np.linalg.norm(acc[:2])
        if lateral > acc[2] * tan_max:
            acc[:2] *= acc[2] * tan_max / lateral
        norm = np.linalg.norm(acc)
        if norm > self.thrust_frac * self.a_max:
            acc *= self.thrust_frac * self.a_max / norm

        z_body = Rotation.from_quat(obs["quat"]).as_matrix()[:, 2]
        thrust = self.mass * max(float(acc @ z_body), 0.0)
        self._last_thrust = thrust
        z_des = acc / np.linalg.norm(acc)
        y_des = np.cross(z_des, [1.0, 0.0, 0.0])
        y_des /= np.linalg.norm(y_des)
        x_des = np.cross(y_des, z_des)
        rpy = Rotation.from_matrix(np.c_[x_des, y_des, z_des]).as_euler("xyz")
        return np.r_[rpy, thrust].astype(np.float32)

    def _mpc_control(self, obs: dict, t: float, r: float) -> np.ndarray:
        """Track the plan (+ gate offsets, at clock rate r) over the horizon with the MPC."""
        from crazyflow.dynamics.utils.rotation import ang_vel2rpy_rates

        poles = np.asarray(obs["obstacles_pos"])[:, :2]
        solver, nx, nu = _build_mpc(self._drone, self.mpc_N, self.dt, tuple(self.mpc_weights),
                                    float(np.deg2rad(self.max_tilt_deg)), len(poles),
                                    float(self.mpc_pole_r), float(self.mpc_pole_penalty),
                                    float(self.mpc_frame_r))
        frames = []
        for k in (self.segment - 1, self.segment):  # gate just passed and next gate
            g = self.sequence[min(max(k, 0), len(self.sequence) - 1)]
            Rg = Rotation.from_quat(obs["gates_quat"][g]).as_matrix()
            frames.append(np.asarray(obs["gates_pos"][g]) + FRAME_LOCAL @ Rg[:, 1:3].T)
        params = np.r_[poles.ravel(), np.concatenate(frames).ravel()]
        rpy = Rotation.from_quat(obs["quat"]).as_euler("xyz")
        drpy = ang_vel2rpy_rates(obs["quat"], obs["ang_vel"])
        x0 = np.concatenate([obs["pos"], rpy, obs["vel"], drpy, self._last_u])
        solver.set(0, "lbx", x0)
        solver.set(0, "ubx", x0)
        for j in range(self.mpc_N + 1):
            if self.mpc_pole_r > 0 or self.mpc_frame_r > 0:
                solver.set(j, "p", params)
            tj = t + j * self.dt * r
            p, v, a = self._ref(tj)
            o, ov, oa = self._offset(tj)
            acc = (a + GRAVITY + oa) * r**2 - GRAVITY  # thrust acceleration at this rate
            acc[2] = max(acc[2], 0.5)
            att = _accel_to_rpy(acc)
            u_ref = np.concatenate([att, [self.mass * np.linalg.norm(acc)]])
            x_ref = np.concatenate([p + o, att, (v + ov) * r, np.zeros(3), u_ref])
            if not self._mpc_warm:  # first call: start the solver from the reference itself
                solver.set(j, "x", x0 if j == 0 else x_ref)
            if j < self.mpc_N:
                solver.set(j, "yref", np.concatenate([x_ref, np.zeros(4)]))
                if not self._mpc_warm:
                    solver.set(j, "u", np.zeros(4))
            else:
                solver.set(j, "yref", x_ref)
        solver.solve()
        self._mpc_warm = True
        u = solver.get(1, "x")[12:16]  # the command reached after one step of the chosen rate
        self._last_u = np.asarray(u, dtype=float)
        self._last_thrust = float(u[3])
        return np.asarray(u, dtype=np.float32)

    def step_callback(self, action, obs, reward, terminated, truncated, info) -> bool:  # noqa: D102
        self.t += self.dt * self.rate
        return int(obs["n_gates_passed"]) >= len(self.sequence)

    def episode_callback(self):
        """Reset between episodes."""
        self.t, self.rate = 0.0, 1.0
        self.integral[:] = 0
