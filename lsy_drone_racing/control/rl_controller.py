"""Level 2 race controller: minimum-time racing line + attitude-mode tracking.

How it works:
1. PLAN: a minimum-time trajectory for the nominal track (point-mass model, solved offline with
   CasADi in rl_spline/min_time.py) is embedded below as per-leg durations and thrust
   accelerations. Integrating them from the start position gives the reference position and
   velocity, so the reference is dynamically consistent by construction.
2. GATE CORRECTION: gate positions are exact only within 0.7 m. When a gate's true position is
   revealed, a cubic offset path is planned from the current offset to that gate's shift, ending
   at the planned crossing time; its acceleration is fed forward. The start offset fades out
   the same way before the first gate.
3. TRACKING (attitude mode): desired acceleration = plan acceleration (slightly ahead, to cover
   attitude lag) + offset acceleration + PID feedback; converted to collective thrust and
   roll/pitch with yaw 0.

Requires `control_mode = "attitude"`. Uses only numpy/scipy/crazyflow at race time.
"""

